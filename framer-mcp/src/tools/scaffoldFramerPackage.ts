import fs from "fs-extra";
import path from "path";
import { z } from "zod";
import { bold, green, yellow } from "kolorist";

export const scaffoldFramerPackage = async (args: unknown) => {
  const schema = z.object({
    targetDir: z.string(),
    packageName: z.string(),
    author: z.string().optional(),
  });
  const { targetDir, packageName, author } = schema.parse(args);

  const pkgRoot = path.resolve(targetDir);
  const srcDir = path.join(pkgRoot, "code");

  await fs.ensureDir(srcDir);

  const packageJson = {
    name: packageName,
    version: "0.1.0",
    private: true,
    main: "code/index.ts",
    devDependencies: {
      typescript: "^5.6.3",
    },
  };

  const indexTs = `export * from './components';\n`;
  const componentsIndex = `// re-export components here\n`;
  const readme = `# ${packageName}\n\nGenerated by framer-mcp.\n`;

  await Promise.all([
    fs.writeJson(path.join(pkgRoot, "package.json"), packageJson, {
      spaces: 2,
    }),
    fs.writeFile(path.join(pkgRoot, "README.md"), readme),
    fs.ensureDir(path.join(srcDir, "components")),
    fs.writeFile(path.join(srcDir, "index.ts"), indexTs),
    fs.writeFile(path.join(srcDir, "components", "index.ts"), componentsIndex),
  ]);

  return {
    message: `${green("Framer package scaffolded at")} ${bold(pkgRoot)}`,
    pkgRoot,
  };
};
